log = logging.getLogger(__name__)


MANT_SCENARIO_ID = 4


def slugify(value):
    text = re.sub(r"[^a-zA-Z0-9._ -]+", "", str(value or "").strip())
    text = re.sub(r"\s+", " ", text).strip()
    return text or "preset"


def split_csv(value):
    if isinstance(value, list):
        return value
    return [part.strip() for part in str(value or "").split(",") if part.strip()]


def normalize_skill_list(value):
    rows = value if isinstance(value, list) else []
    result = []
    for row in rows:
        if isinstance(row, list):
            parts = []
            for item in row:
                parts.extend(split_csv(item))
        else:
            parts = split_csv(row)
        if parts:
            result.append(parts)
    return result


def as_int(value, default):
    try:
        return int(value)
    except (TypeError, ValueError):
        return default


def normalize_race_list(value):
    result = []
    for item in value if isinstance(value, list) else []:
        race_id = as_int(item, None)
        if race_id is not None:
            result.append(race_id)
    return result


def stored_scenario_id(raw):
    """The scenario id a stored/incoming preset already carries, else None.

    Presets carry the id under 'scenario_id' or the legacy 'scenario' alias; 0
    and unparseable values mean "unset", matching
    ``career_bot.scenarios.resolve_scenario_id``. None (not a default) is
    returned for legacy presets written before the id was persisted, so
    hydrate_preset can tell "no stored scenario" apart from "stored MANT".
    """
    data = raw or {}
    for key in ("scenario_id", "scenario"):
        sid = as_int(data.get(key), None)
        if sid:
            return sid
    return None


def serialize_preset(raw):
    data = dict(raw or {})
    serialized = {}

    serialized["name"] = slugify(data.get("name") or "preset")
    serialized["running_style"] = as_int(data.get("running_style"), 1)
    serialized["learn_skill_list"] = normalize_skill_list(data.get("learn_skill_list"))

    blacklist = []
    blacklist.extend(split_csv(data.get("blacklistedSkills")))
    blacklist.extend(split_csv(data.get("skill_blacklist")))
    blacklist.extend(split_csv(data.get("learn_skill_blacklist")))
    serialized["learn_skill_blacklist"] = list(dict.fromkeys(blacklist))

    serialized["extra_race_list"] = normalize_race_list(data.get("extra_race_list", data.get("race_list", [])))
    serialized["learn_skill_threshold"] = as_int(data.get("learn_skill_threshold"), 888)
    for key in ("sirius_throne_schedule",):
        if key in data:
            serialized[key] = data[key]

    # Persist the scenario the preset runs under so a non-MANT preset survives a
    # save/load round-trip. Only the canonical 'scenario_id' is written (the
    # legacy 'scenario' alias is regenerated by hydrate_preset); the key is
    # omitted entirely when the source carries no scenario, which keeps legacy
    # preset files -- and their hydration -- byte-identical.
    sid = stored_scenario_id(data)
    if sid is not None:
        serialized["scenario_id"] = sid

    return serialized

def hydrate_preset(raw):
    data = serialize_preset(raw)

    # Respect a persisted scenario id; fall back to MANT for legacy presets that
    # never stored one (and for ids no registered strategy claims, so a
    # hand-edited file can't hand the runner an unrunnable scenario).
    # Lazy import: career_bot.scenarios pulls in bot_config, which imports this
    # module's package siblings -- see career_bot/bot_config/apply.py.
    from career_bot.scenarios import get_strategy_class
    sid = data.get("scenario_id") or MANT_SCENARIO_ID
    if get_strategy_class(sid) is None:
        sid = MANT_SCENARIO_ID
    data["scenario_id"] = sid
    data["scenario"] = sid
    data["cure_asap_conditions"] = copy.deepcopy(MANT_DEFAULTS["cure_asap_conditions"])
    data["expect_attribute"] = copy.deepcopy(MANT_DEFAULTS["expect_attribute"])
    data["score_value"] = copy.deepcopy(MANT_DEFAULTS["score_value"])
    data["base_score"] = copy.deepcopy(MANT_DEFAULTS["base_score"])
    data["stat_value_multiplier"] = copy.deepcopy(MANT_DEFAULTS["stat_value_multiplier"])
    data["extra_weight"] = copy.deepcopy(MANT_DEFAULTS["extra_weight"])
    data["npc_score_value"] = copy.deepcopy(MANT_DEFAULTS["npc_score_value"])
    # special_training / spirit_explosion / wit_special_multiplier were seeded
    # here until bot-config schema v2 dropped them (§12.6) -- nothing ever read
    # them back off the runtime preset.
    data["compensate_failure"] = copy.deepcopy(MANT_DEFAULTS["compensate_failure"])
    data["summer_score_threshold"] = copy.deepcopy(MANT_DEFAULTS["summer_score_threshold"])
    data["motivation_threshold_year1"] = copy.deepcopy(MANT_DEFAULTS["motivation_threshold_year1"])
    data["motivation_threshold_year2"] = copy.deepcopy(MANT_DEFAULTS["motivation_threshold_year2"])
    data["motivation_threshold_year3"] = copy.deepcopy(MANT_DEFAULTS["motivation_threshold_year3"])
    data["prioritize_recreation"] = copy.deepcopy(MANT_DEFAULTS["prioritize_recreation"])
    data["pal_thresholds"] = copy.deepcopy(MANT_DEFAULTS["pal_thresholds"])
    data["rest_threshold"] = copy.deepcopy(MANT_DEFAULTS["rest_threshold"])
    data["buy_notepads"] = copy.deepcopy(MANT_DEFAULTS["buy_notepads"])
    data["manual_purchase_at_end"] = copy.deepcopy(MANT_DEFAULTS["manual_purchase_at_end"])
    data["mant_config"] = {}

    return data

def apply_race_preset(preset, race_preset):
    """Return a copy of preset with extra_race_list overridden from race_preset."""
    result = dict(preset)
    if race_preset:
        result["extra_race_list"] = list(race_preset.get("extra_race_list", []))
    return result


def serialize_race_preset(raw):
    data = dict(raw or {})
    return {
        "name": slugify(data.get("name") or "races"),
        "extra_race_list": normalize_race_list(
            data.get("extra_race_list", data.get("races", []))
        ),
    }


class _JsonPresetStore:
    """One-JSON-file-per-preset store, shared by the race and skill preset stores.

    Directory layout, discovery, name lookup, write and delete are identical for
    both; the subclasses differ only in three hooks:
      `subdir`        - which folder under data/ holds the files
      `_load(raw)`    - how a file's JSON becomes the returned preset
      `_dump(preset)` - what gets persisted
      `_written(...)` - what write() returns (race returns the serialized form,
                        skill returns the hydrated one -- they are NOT the same)
    """

    subdir = ""

    def __init__(self, state_root, source_root=None):
        self.state_root = Path(state_root)
        self.preset_dir = self.state_root / self.subdir
        self.legacy_preset_dir = (
            Path(source_root) / "data" / self.subdir
            if source_root is not None else None
        )

    def _load(self, raw):
        raise NotImplementedError

    def _dump(self, preset):
        raise NotImplementedError

    def _written(self, serialized):
        return serialized

    def ensure(self):
        ensure_private_dir(self.preset_dir)

    def read_all(self):
        self.ensure()
        loaded = {}
        for path in self._source_files():
            try:
                data = self._load(json.loads(path.read_text(encoding="utf-8")))
            # read_text -> OSError / UnicodeDecodeError(ValueError); json.loads ->
            # ValueError; _load starts with dict(raw or {}), which raises
            # TypeError/ValueError when the file's JSON is not an object.
            except (OSError, ValueError, TypeError):
                continue
            loaded[data["name"]] = data
        return sorted(loaded.values(), key=lambda item: item["name"].lower())

    def read_one(self, name):
        wanted = str(name or "").strip().lower()
        for preset in self.read_all():
            if preset["name"].lower() == wanted:
                return preset
        return None

    def write(self, preset):
        self.ensure()
        serialized = self._dump(preset)
        path = self.preset_dir / f"{slugify(serialized['name'])}.json"
        atomic_write_private_text(
            path,
            json.dumps(serialized, ensure_ascii=False, indent=2),
        )
        return self._written(serialized)

    def delete(self, name):
        path = self.preset_dir / f"{slugify(name)}.json"
        if path.exists():
            path.unlink()
            return True
        return False

    def _source_files(self):
        if self.preset_dir.exists():
            files = list(self.preset_dir.glob("*.json"))
            if files:
                return files
        if self.legacy_preset_dir is not None and self.legacy_preset_dir.exists():
            return list(self.legacy_preset_dir.glob("*.json"))
        return []

    def migrate_legacy(self):
        if self.legacy_preset_dir is None or not self.legacy_preset_dir.exists():
            return 0
        self.ensure()
        count = 0
        for source in self.legacy_preset_dir.glob("*.json"):
            try:
                loaded = self._load(json.loads(source.read_text(encoding="utf-8")))
                serialized = self._dump(loaded)
                destination = self.preset_dir / f"{slugify(serialized['name'])}.json"
                if destination.exists():
                    continue
                atomic_write_private_text(
                    destination,
                    json.dumps(serialized, ensure_ascii=False, indent=2),
                )
                count += 1
            except (OSError, ValueError, TypeError):
                continue
        if count:
            log.info(
                "Migrated %d legacy %s preset(s) from %s to %s",
                count,
                self.subdir,
                self.legacy_preset_dir,
                self.preset_dir,
            )
        return count


class RacePresetStore(_JsonPresetStore):
    subdir = "race_presets"

    def _load(self, raw):
        return serialize_race_preset(raw)

    def _dump(self, preset):
        return serialize_race_preset(preset)


def migrate_race_presets(state_root, source_root=None):
    """Migrate extra_race_list from skill presets into race presets (idempotent)."""
    base = Path(state_root)
    race_dir = base / "race_presets"
    try:
        skill_store = PresetStore(state_root, source_root)
        race_store = RacePresetStore(state_root, source_root)
        count = skill_store.migrate_legacy() + race_store.migrate_legacy()
        ensure_private_dir(race_dir)
        existing = list(race_dir.glob("*.json"))
        if existing:
            return count  # already migrated — idempotent guard
        for preset in skill_store.read_all():
            races = preset.get("extra_race_list") or []
            if races:
                try:
                    race_store.write({"name": f"{preset['name']} races", "extra_race_list": races})
                    count += 1
                # write() only touches the filesystem here (mkdir + write_text) with a
                # literal, JSON-safe payload -> OSError, or UnicodeEncodeError(ValueError)
                # on an unencodable preset name. Anything else still lands in the
                # surrounding broad handler, so the fallback is unchanged.
                except (OSError, ValueError):
                    pass
        return count
    except Exception:
        return 0


class PresetStore(_JsonPresetStore):
    subdir = "presets"

    def _load(self, raw):
        return hydrate_preset(raw)

    def _dump(self, preset):
        return serialize_preset(preset)

    def _written(self, serialized):
        # Persists the serialized form but hands back the hydrated one.
        return hydrate_preset(serialized)
